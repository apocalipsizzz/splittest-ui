/**
 * SVG из src/icons/svg → React-компоненты в src/icons.
 * Размер берётся из SVG (иконки 20×20, галерея 20×40). width/height в пропсах
 * перекрывают его. icon/control — currentColor, label и logo — свои заливки.
 * У illustration чёрный stroke становится currentColor.
 * Файл с пустым сегментом имени (illustration_test_.svg) пропускается.
 */
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = join(root, 'src/icons/svg');
const outDir = join(root, 'src/icons');
const banner = '// Generated by scripts/build-icons.mjs. Do not edit.';

const reactName = name => {
  if (
    name === 'viewBox' ||
    name.startsWith('data-') ||
    name.startsWith('aria-')
  ) {
    return name;
  }

  return name.replace(/[:_-]([a-zA-Z0-9])/g, (_, char) => char.toUpperCase());
};

const jsxString = value => {
  if (value.includes('"') || value.includes('\\') || value.includes('\n')) {
    return `{${JSON.stringify(value)}}`;
  }

  return `"${value}"`;
};

const styleLiteral = (value, file) => {
  const fields = value
    .split(';')
    .map(part => part.trim())
    .filter(Boolean)
    .map(part => {
      const splitAt = part.indexOf(':');
      if (splitAt === -1) throw new Error(`${file}: bad style ${value}`);
      const key = reactName(part.slice(0, splitAt).trim());
      const styleValue = part.slice(splitAt + 1).trim();
      return `${key}: ${JSON.stringify(styleValue)}`;
    });

  return `{ ${fields.join(', ')} }`;
};

const decode = value =>
  value
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');

const parse = (source, file) => {
  const text = source.replace(/<!--[\s\S]*?-->/g, '');
  let index = 0;

  const skipWs = () => {
    while (/\s/.test(text[index] ?? '')) index += 1;
  };

  const parseTag = () => {
    skipWs();
    if (text[index] !== '<') {
      throw new Error(
        `${file}: expected < at ${index}: ${text.slice(index, index + 30)}`,
      );
    }

    index += 1;
    const closing = text[index] === '/';
    if (closing) index += 1;

    const nameStart = index;
    while (/[\w:-]/.test(text[index] ?? '')) index += 1;
    const name = text.slice(nameStart, index);
    if (!name) throw new Error(`${file}: missing tag name`);

    const attrs = [];
    while (index < text.length) {
      while (/\s/.test(text[index] ?? '')) index += 1;
      if (
        text[index] === '>' ||
        text[index] === '/' ||
        text[index] === undefined
      )
        break;

      const attrStart = index;
      while (/[\w:-]/.test(text[index] ?? '')) index += 1;
      const attrName = text.slice(attrStart, index);
      if (!attrName) {
        throw new Error(
          `${file}: bad attribute at ${text.slice(index, index + 20)}`,
        );
      }

      while (/\s/.test(text[index] ?? '')) index += 1;
      if (text[index] !== '=')
        throw new Error(`${file}: expected = after ${attrName}`);
      index += 1;
      while (/\s/.test(text[index] ?? '')) index += 1;

      const quote = text[index];
      if (quote !== '"' && quote !== "'")
        throw new Error(`${file}: unquoted ${attrName}`);
      index += 1;
      const valueStart = index;
      while (index < text.length && text[index] !== quote) index += 1;
      if (text[index] !== quote)
        throw new Error(`${file}: unclosed ${attrName}`);
      attrs.push({
        name: attrName,
        value: decode(text.slice(valueStart, index)),
      });
      index += 1;
    }

    const selfClosing = text[index] === '/';
    if (selfClosing) index += 1;
    if (text[index] !== '>') throw new Error(`${file}: unclosed <${name}>`);
    index += 1;

    if (closing) return { closing: true, name, attrs, children: [] };

    const children = [];
    if (!selfClosing) {
      while (index < text.length) {
        skipWs();
        if (text.startsWith('</', index)) {
          const end = parseTag();
          if (!end.closing || end.name !== name) {
            throw new Error(`${file}: <${name}> closed by ${end.name}`);
          }
          break;
        }

        if (text[index] !== '<') {
          const textStart = index;
          while (index < text.length && text[index] !== '<') index += 1;
          const raw = text.slice(textStart, index).trim();
          if (raw) throw new Error(`${file}: unexpected text in <${name}>`);
          continue;
        }

        children.push(parseTag());
      }
    }

    return { closing: false, name, attrs, children };
  };

  skipWs();
  const root = parseTag();
  skipWs();
  if (index !== text.length) {
    throw new Error(`${file}: trailing ${text.slice(index, index + 30)}`);
  }
  if (root.name !== 'svg') throw new Error(`${file}: root is ${root.name}`);

  return root;
};

const attrValue = (node, name) =>
  node.attrs.find(attr => attr.name === name)?.value;

const walk = (node, visit) => {
  visit(node);
  for (const child of node.children) walk(child, visit);
};

const px = (value, file, fallback) => {
  const source = value ?? fallback;
  if (source === undefined) throw new Error(`${file}: missing size`);
  const number = Number(String(source).replace(/px$/, ''));
  if (!Number.isFinite(number)) throw new Error(`${file}: bad size ${source}`);
  return number;
};

const kindOf = stem => {
  if (stem.startsWith('illustration_')) return 'illustration';
  if (stem.startsWith('logo_')) return 'logo';
  if (stem.startsWith('control_')) return 'control';
  if (stem.startsWith('icon_'))
    return stem.includes('label-') ? 'brand' : 'icon';
  throw new Error(`unknown icon prefix: ${stem}`);
};

const emitAttrs = (attrs, idVars) => {
  const parts = [];

  for (const attr of attrs) {
    if (attr.name === 'id') {
      const varName = idVars.get(attr.value);
      if (varName) parts.push(`id={${varName}}`);
      continue;
    }

    const url = /^url\(#(.+)\)$/.exec(attr.value);
    if (url) {
      const varName = idVars.get(url[1]);
      if (!varName) throw new Error(`missing id ${url[1]}`);
      parts.push(`${reactName(attr.name)}={\`url(#\${${varName}})\`}`);
      continue;
    }

    if (attr.name === 'style') {
      parts.push(`style={${styleLiteral(attr.value, 'svg')}}`);
      continue;
    }

    parts.push(`${reactName(attr.name)}=${jsxString(attr.value)}`);
  }

  return parts.length ? ` ${parts.join(' ')}` : '';
};

const emitNode = (node, indent, idVars) => {
  const pad = ' '.repeat(indent);
  const attrs = emitAttrs(node.attrs, idVars);
  if (!node.children.length) return `${pad}<${node.name}${attrs} />`;

  const inner = node.children
    .map(child => emitNode(child, indent + 2, idVars))
    .join('\n');
  return `${pad}<${node.name}${attrs}>\n${inner}\n${pad}</${node.name}>`;
};

const componentSource = ({ name, svgProps, body, idVars }) => {
  const props = svgProps.join(' ');

  if (!idVars.size) {
    return `${banner}
import { Svg, type IconProps } from './svg';

export const ${name} = (props: IconProps) => (
  <Svg ${props} {...props}>
${body}
  </Svg>
);
`;
  }

  const ids = [...idVars.entries()]
    .map(([raw, varName]) => `  const ${varName} = \`\${rawId}-${raw}\`;`)
    .join('\n');

  return `${banner}
import { useId } from 'react';

import { Svg, type IconProps } from './svg';

export const ${name} = (props: IconProps) => {
  const rawId = useId().replace(/:/g, '');
${ids}

  return (
    <Svg ${props} {...props}>
${body}
    </Svg>
  );
};
`;
};

for (const file of readdirSync(outDir)) {
  if (!file.endsWith('.ts') && !file.endsWith('.tsx')) continue;
  if (
    file === 'svg.tsx' ||
    file.endsWith('.stories.tsx') ||
    file.endsWith('.test.tsx')
  ) {
    continue;
  }

  const full = join(outDir, file);
  if (readFileSync(full, 'utf8').startsWith(banner)) rmSync(full);
}

const exports = [];
const skipped = [];

for (const file of readdirSync(svgDir).sort()) {
  if (!file.endsWith('.svg')) continue;

  const stem = file.slice(0, -'.svg'.length);
  const segments = stem.split(/[_-]/);
  if (segments.some(segment => segment.length === 0)) {
    skipped.push(file);
    console.log(`icons: skip ${file}`);
    continue;
  }

  const kind = kindOf(stem);
  let source = readFileSync(join(svgDir, file), 'utf8');
  if (kind === 'illustration') {
    source = source.replace(
      /stroke=['"]#(?:000000|000)['"]/gi,
      'stroke="currentColor"',
    );
  }

  const root = parse(source, file);
  const viewBox = attrValue(root, 'viewBox');
  if (!viewBox) throw new Error(`${file}: missing viewBox`);

  const box = viewBox.trim().split(/\s+/).map(Number);
  if (box.length !== 4 || box.some(value => !Number.isFinite(value))) {
    throw new Error(`${file}: bad viewBox ${viewBox}`);
  }

  const [, , boxWidth, boxHeight] = box;
  const svgProps = [
    `viewBox="${viewBox}"`,
    `width={${px(attrValue(root, 'width'), file, String(boxWidth))}}`,
    `height={${px(attrValue(root, 'height'), file, String(boxHeight))}}`,
  ];
  if (kind === 'icon' || kind === 'control' || kind === 'illustration') {
    svgProps.push('fill="currentColor"');
  }

  const referenced = new Set();
  walk(root, node => {
    for (const attr of node.attrs) {
      const url = /^url\(#(.+)\)$/.exec(attr.value);
      if (url) referenced.add(url[1]);
    }
  });

  const idVars = new Map();
  for (const id of [...referenced].sort()) {
    let varName = id.replace(/[^\w$]/g, '');
    if (!/^[A-Za-z_$]/.test(varName)) varName = `paint${varName}`;
    idVars.set(id, varName);
  }

  const name = segments
    .map(segment => segment[0].toUpperCase() + segment.slice(1))
    .join('');
  const outFile = `${segments.join('-')}.tsx`;
  const body = root.children
    .map(child => emitNode(child, idVars.size ? 6 : 4, idVars))
    .join('\n');

  if (exports.some(item => item.name === name || item.file === outFile)) {
    throw new Error(`${file}: duplicate ${name}`);
  }

  writeFileSync(
    join(outDir, outFile),
    componentSource({ name, svgProps, body, idVars }),
  );
  exports.push({ name, file: outFile });
}

exports.sort((a, b) => a.name.localeCompare(b.name, 'en'));

writeFileSync(
  join(outDir, 'index.ts'),
  `${banner}
export type { IconProps } from './svg';
${exports.map(item => `export { ${item.name} } from './${item.file.replace(/\.tsx$/, '')}';`).join('\n')}
`,
);

const readOut = name => readFileSync(join(outDir, name), 'utf8');
if (!readOut('icon-close.tsx').includes('fill="currentColor"')) {
  throw new Error('icon-close lost currentColor');
}
const checkbox = readOut('control-mark-checkbox.tsx');
if (!checkbox.includes('width={20}') || !checkbox.includes('height={20}')) {
  throw new Error('checkbox mark is not 20px');
}
const gallery = readOut('icon-gallery-next.tsx');
if (!gallery.includes('width={20}') || !gallery.includes('height={40}')) {
  throw new Error('gallery icon lost 20×40');
}
const illustration = readOut('illustration-test-best.tsx');
if (
  !illustration.includes('stroke="currentColor"') ||
  !illustration.includes('fill="currentColor"')
) {
  throw new Error('illustration was not retinted');
}
if (readOut('logo-visa.tsx').includes('currentColor')) {
  throw new Error('logo was retinted');
}
if (!readOut('icon-label-wildberries.tsx').includes('useId')) {
  throw new Error('gradient id is not unique');
}
if (
  readdirSync(svgDir).includes('illustration_test_.svg') &&
  !skipped.includes('illustration_test_.svg')
) {
  throw new Error('illustration_test_.svg should be skipped');
}

const generated = [
  join(outDir, 'index.ts'),
  ...exports.map(item => join(outDir, item.file)),
];
const formatted = spawnSync('pnpm', ['exec', 'oxfmt', ...generated], {
  cwd: root,
  stdio: 'inherit',
});
if (formatted.status !== 0) process.exit(formatted.status ?? 1);

console.log(`icons: ${exports.length} components, skipped ${skipped.length}`);
